    def spawn_worker(job_id: int) -> bool:
        with lock:
            if job_id in running:
                return False
            running.add(job_id)

        def worker() -> None:
            worker_gate.acquire()
            try:
                result = orch.run_job(
                    job_id,
                    progress_cb=lambda phase, jid: hub.publish(jid, {"phase": phase}))
                if result.get("waiting_voice"):
                    hub.publish(job_id, {"phase": "waiting_voice"})
                elif result.get("paused"):
                    hub.publish(job_id, {"phase": "paused_review"})
                else:
                    m = result["manifest"]
                    hub.publish(job_id, {"phase": "done",
                                         "video": m["artifacts"]["video"]["path"]})
            except Exception as exc:  # noqa: BLE001 - report through stream
                from atme.audio.voice_upload import VoiceScriptMismatch
                from atme.orchestrator import JobCanceled, JobPaused

                if isinstance(exc, JobPaused):
                    hub.publish(job_id, {"phase": "paused"})
                    return
                if isinstance(exc, JobCanceled):
                    hub.publish(job_id, {"phase": "canceled"})
                    return
                if isinstance(exc, VoiceScriptMismatch):
                    store.set_job_status(job_id, "voice_rejected")
                    store.log(job_id, str(exc), level="error")
                    hub.publish(job_id, {"phase": "voice_rejected",
                                         "error": str(exc)[:300]})
                    return
                log.exception("job %s failed", job_id)
                store.set_job_status(job_id, "failed")
                store.log(job_id, str(exc)[:500], level="error")
                hub.publish(job_id, {"phase": "failed", "error": str(exc)[:300]})
            finally:
                worker_gate.release()
                with lock:
                    running.discard(job_id)

        threading.Thread(target=worker, daemon=True).start()
        return True

    @app.post("/jobs/{job_id}/run", dependencies=[Depends(auth)])
    def run_job(job_id: int) -> dict:
        if orch is None:
            raise HTTPException(503, "orchestrator not wired into this sidecar instance")
        accepted = spawn_worker(job_id)
        return {"accepted": accepted, **({} if accepted else {"reason": "already running"})}

    @app.post("/jobs/{job_id}/control", dependencies=[Depends(auth)])
    def control_job(job_id: int, body: dict) -> dict:
        job = store.get_job(job_id)
        if not job:
            raise HTTPException(404, "no such job")
        action = str(body.get("action") or "").lower()
        if action == "pause":
            if job["status"] not in ("running", "pause_requested"):
                raise HTTPException(409, "only a running job can be paused")
            store.set_job_status(job_id, "pause_requested")
            hub.publish(job_id, {"phase": "pause_requested"})
            return {"accepted": True, "status": "pause_requested"}
        if action == "resume":
            if job["status"] not in ("paused", "failed"):
                raise HTTPException(409, "only a paused or failed job can be resumed")
            store.set_job_status(job_id, "running")
            return {"accepted": spawn_worker(job_id), "status": "running"}
        if action == "cancel":
            if job["status"] in ("done", "canceled"):
                raise HTTPException(409, "job is already terminal")
            with lock:
                active = job_id in running
            status = "cancel_requested" if active else "canceled"
            store.set_job_status(job_id, status)
            hub.publish(job_id, {"phase": status})
            return {"accepted": True, "status": status}
        raise HTTPException(400, "action must be pause, resume, or cancel")

    @app.post("/jobs/{job_id}/review", dependencies=[Depends(auth)])
    def review(job_id: int, body: dict) -> dict:
        if not store.get_job(job_id):
            raise HTTPException(404, "no such job")
        approved = bool(body.get("approved"))
        if not approved:
            store.set_job_status(job_id, "canceled")
            return {"accepted": True, "status": "canceled"}
        # Optional scene edits: replace script.json scenes wholesale.
        scenes = body.get("scenes")
        jdir = orch._job_dir(job_id) if orch is not None else None
        if scenes is not None and jdir is not None:
            sp = jdir / "script.json"
            if sp.exists():
                doc = json.loads(sp.read_text(encoding="utf-8"))
                if store.get_job(job_id)["settings"].get("provider") == "external" and scenes != doc["scenes"]:
                    raise HTTPException(409, "external script changed; import a revised script and matching layout as a new project")
                doc["scenes"] = scenes
                from jsonschema import Draft202012Validator
                from atme.resources import resource_path

                schema = json.loads(resource_path(
                    "schemas", "script-scenes.schema.json").read_text(encoding="utf-8"))
                errors = [error.message for error in
                          Draft202012Validator(schema).iter_errors(doc)]
                scene_ids = [scene.get("scene_id") for scene in scenes
                             if isinstance(scene, dict)]
                if len(scene_ids) != len(set(scene_ids)):
                    errors.append("scene_id values must be unique")
                if errors:
                    raise HTTPException(400, "invalid edited script: " + "; ".join(errors[:5]))
                sp.write_text(json.dumps(doc, indent=2), encoding="utf-8")
        store.start_stage(job_id, "reviewed")
        if jdir is not None and (jdir / "script.json").exists():
            orch._attach_file(job_id, "reviewed", "approved_script", jdir / "script.json")
        store.finish_stage(job_id, "reviewed", ok=True)
        job = store.get_job(job_id)
        if job and job["settings"].get("voice") == "upload" and not (
                orch._job_dir(job_id) / "audio" / "upload.wav").exists():
            store.set_job_status(job_id, "waiting_voice")
            hub.publish(job_id, {"phase": "waiting_voice"})
            return {"accepted": True, "status": "waiting_voice", "resumed": False}
        store.set_job_status(job_id, "running")
        hub.publish(job_id, {"phase": "review_approved"})
        spawned = spawn_worker(job_id) if orch is not None else False
        return {"accepted": True, "status": "running", "resumed": spawned}

    @app.post("/jobs/{job_id}/voice", dependencies=[Depends(auth)])
    async def upload_voice(job_id: int, request: Request,
                           x_filename: str = Header(default="voice.wav")) -> dict:
        if orch is None:
            raise HTTPException(503, "orchestrator not wired")
        job = store.get_job(job_id)
        if not job:
            raise HTTPException(404, "no such job")
        if job["settings"].get("voice") != "upload":
            raise HTTPException(409, "job is not configured for uploaded voice")
        from atme.audio.voice_upload import (MAX_UPLOAD_BYTES, VoiceUploadError,
                                             replace_uploaded_file)

        length = request.headers.get("content-length")
        try:
            if length and int(length) > MAX_UPLOAD_BYTES:
                raise HTTPException(413, "voiceover exceeds the 1 GB limit")
        except ValueError as exc:
            raise HTTPException(400, "invalid content-length") from exc

        audio_dir = orch._job_dir(job_id) / "audio"
        audio_dir.mkdir(parents=True, exist_ok=True)
        staged = audio_dir / ".voice-upload.part"
        received = 0
        try:
            with staged.open("wb") as fh:
                async for chunk in request.stream():
                    received += len(chunk)
                    if received > MAX_UPLOAD_BYTES:
                        raise HTTPException(413, "voiceover exceeds the 1 GB limit")
                    fh.write(chunk)
            source, quality = replace_uploaded_file(
                orch._job_dir(job_id), x_filename, staged)
        except HTTPException:
            staged.unlink(missing_ok=True)
            raise
        except VoiceUploadError as exc:
            staged.unlink(missing_ok=True)
            raise HTTPException(400, str(exc)) from exc
        except OSError as exc:
            staged.unlink(missing_ok=True)
            raise HTTPException(500, "could not store the voiceover") from exc

        store.reset_from_stage(job_id, "voiced")
        store.set_job_status(job_id, "running")
        store.log(job_id, "uploaded original voiceover: %s" % source.name)
        spawned = spawn_worker(job_id)
        return {"accepted": spawned, "status": "running", "quality": quality}

