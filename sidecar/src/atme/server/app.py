    @app.get("/jobs/{job_id}", dependencies=[Depends(auth)])
    def job_state(job_id: int) -> dict:
        job = store.get_job(job_id)
        if not job:
            raise HTTPException(404, "no such job")
        first, done = store.resume_point(job_id)
        with store._lock:
            rows = store.conn.execute(
                "SELECT s.name,s.status,s.attempt,s.error FROM stages s "
                "JOIN (SELECT name,MAX(attempt) attempt FROM stages WHERE job_id=? "
                "GROUP BY name) latest ON latest.name=s.name AND latest.attempt=s.attempt "
                "WHERE s.job_id=? ORDER BY s.rowid", (job_id, job_id)).fetchall()
        stages = sorted((dict(r) for r in rows),
                        key=lambda item: STAGE_ORDER.index(item["name"]))
        return {"job": job, "stages": stages,
                "resume_point": first, "done_stages": done}

