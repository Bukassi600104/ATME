log = logging.getLogger(__name__)


class JobHub:
    """In-process pub/sub for job progress events."""

    def __init__(self) -> None:
        self._subs: dict[int, list["queue.Queue"]] = {}
        self._lock = threading.Lock()

    def subscribe(self, job_id: int) -> queue.Queue:
        q: queue.Queue = queue.Queue()
        with self._lock:
            self._subs.setdefault(job_id, []).append(q)
        return q

    def publish(self, job_id: int, event: dict) -> None:
        with self._lock:
            subs = list(self._subs.get(job_id, []))
        for q in subs:
            q.put(event)

    def unsubscribe(self, job_id: int, q: queue.Queue) -> None:
        with self._lock:
            if job_id in self._subs and q in self._subs[job_id]:
                self._subs[job_id].remove(q)


def _auth_dependency(token: str):
    def check(authorization: str = Header(default="")) -> None:
        expected = "Bearer %s" % token
        if authorization != expected:
            raise HTTPException(status_code=401, detail="bad token")
    return check


