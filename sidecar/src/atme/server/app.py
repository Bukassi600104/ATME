"""Loopback HTTP surface between the Tauri host and this sidecar.

Security model: bind 127.0.0.1 only (uvicorn invocation, M4), ephemeral port, bearer token
generated by the Rust host and passed via env. Every route requires the token EXCEPT /healthz.
Progress streams over SSE so the Run Line UI animates live.
"""

from __future__ import annotations

