    @app.get("/jobs/{job_id}/preview/{scene_id}", dependencies=[Depends(auth)])
    def scene_preview(job_id: int, scene_id: int):
        jdir = orch._job_dir(job_id) if orch is not None else None
        if jdir is None:
            raise HTTPException(503, "orchestrator not wired")
        sp = jdir / "script.json"
        if not sp.exists():
            raise HTTPException(404, "script not ready")
        script = json.loads(sp.read_text(encoding="utf-8"))
        if scene_id not in {int(scene["scene_id"]) for scene in script["scenes"]}:
            raise HTTPException(404, "scene not found")
        starts, cursor = [], 0
        for scene in script["scenes"]:
            starts.append(cursor)
            cursor += int((scene.get("est_seconds") or
                           len(scene["spoken_text"].split()) / 2.5) * 1000)
        from atme.render.animator import build_draw_windows
        from atme.render.autolayout import build_layout
        from atme.render.svg_builder import (element_stroke_info, frame_svg)
        from fastapi.responses import Response

        layout_file = jdir / "layout.json"
        actual_layout = layout_file.exists()
        if actual_layout:
            doc = json.loads(layout_file.read_text(encoding="utf-8"))
        else:
            doc = build_layout(script["scenes"], starts, title=script.get("title"))
            doc["elements"] = [element for element in doc["elements"]
                               if int(element["scene_id"]) <= scene_id]
        infos = {element["id"]: element_stroke_info(element, int(doc["seed"]))
                 for element in doc["elements"]}
        windows = build_draw_windows(doc["elements"])
        selected = [element for element in doc["elements"]
                    if int(element["scene_id"]) == scene_id] if actual_layout else doc["elements"]
        final_ms = max((int(element["appear_at_ms"]) + windows[element["id"]] + 1
                        for element in selected), default=0)
        activations = doc.get("board_timeline", {}).get("activations", [])
        if activations:
            final_ms = min(final_ms, max(a["end_ms"] for a in activations) - 1)
        from atme.render.camera import viewbox_at

        view = (viewbox_at(doc.get("camera_plan", []), doc["canvas"]["width"],
                           doc["canvas"]["height"], final_ms, 640, 360)
                if actual_layout else
                {"x": 0, "y": 0, "w": doc["canvas"]["width"],
                 "h": doc["canvas"]["height"], "out_w": 640, "out_h": 360})
        svg = frame_svg(
            doc, infos, final_ms, windows, view)
        return Response(svg, media_type="image/svg+xml",
                        headers={"Cache-Control": "no-store"})

