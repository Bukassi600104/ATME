    @app.put("/jobs/{job_id}/boards", dependencies=[Depends(auth)])
    async def save_boards(job_id: int, request: Request) -> dict:
        import hashlib
        from uuid import uuid4
        from atme.board_edit import apply_board_edit
        if orch is None:
            raise HTTPException(503, "orchestrator not wired")
        raw = bytearray()
        async for chunk in request.stream():
            raw.extend(chunk)
            if len(raw) > 1024 * 1024:
                raise HTTPException(413, "board edit exceeds 1 MiB")
        try:
            payload = json.loads(raw)
            if not isinstance(payload, dict) or set(payload) != {"revision", "timeline", "assignments"}:
                raise ValueError()
        except ValueError:
            raise HTTPException(400, "invalid board edit request")
        with lock:
            job = store.get_job(job_id)
            if not job:
                raise HTTPException(404, "no such job")
            if job_id in running or job["status"] not in ("paused", "done", "failed", "waiting_voice", "paused_review"):
                raise HTTPException(409, "stop the job before editing boards")
            if "laid_out" not in store.resume_point(job_id)[1]:
                raise HTTPException(409, "finish layout before editing boards")
            directory = orch._job_dir(job_id)
            layout = directory / "layout.json"
            audio = directory / "audio_state.json"
            if not layout.exists() or not audio.exists():
                raise HTTPException(409, "saved layout and final audio required")
            original = layout.read_bytes()
            if hashlib.sha256(original).hexdigest() != payload["revision"]:
                raise HTTPException(409, "layout changed; reload the board editor")
            try:
                doc = apply_board_edit(json.loads(original), payload["timeline"], payload["assignments"],
                                       json.loads(audio.read_text(encoding="utf-8"))["duration_ms"])
            except (ValueError, TypeError, KeyError):
                raise HTTPException(400, "invalid board timeline or element assignment; check intervals, IDs and final-audio bounds")
            revision = uuid4().hex
            (directory / ("layout.before-boards-" + revision + ".json")).write_bytes(original)
            pending = directory / ("layout.boards-" + revision + ".pending.json")
            pending.write_text(json.dumps(doc, indent=2), encoding="utf-8")
            store.reset_from_stage(job_id, "aligned")
            pending.replace(layout)
            store.set_job_status(job_id, "paused")
        return {"saved": True, "status": "paused", "requires_realign": True}

