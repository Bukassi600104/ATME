    @app.post("/jobs/{job_id}/evidence/{element_id}", dependencies=[Depends(auth)])
    @app.put("/jobs/{job_id}/evidence/{element_id}", dependencies=[Depends(auth)])
    async def replace_evidence(job_id: int, element_id: str, request: Request) -> dict:
        if orch is None:
            raise HTTPException(503, "orchestrator not wired")
        # Bound the JSON body before parsing base64. No filenames or paths are accepted.
        body = bytearray()
        async for chunk in request.stream():
            body.extend(chunk)
            if len(body) > 12 * 1024 * 1024:
                raise HTTPException(413, "evidence request exceeds 12 MiB")
        try:
            payload = json.loads(body)
            creating = request.method == "POST"
            required = {"png_base64", "sha256", "provenance"} | ({"placement"} if creating else set())
            if not isinstance(payload, dict) or set(payload) != required:
                raise ValueError()
            placement = payload.pop("placement", None)
            if creating and (not isinstance(placement, dict) or set(placement) != {
                    "scene_id", "board_id", "appear_at_ms", "x", "y", "width", "height"}):
                raise ValueError()
        except (ValueError, UnicodeError):
            raise HTTPException(400, "provide PNG content, checksum and provenance only")
        from atme.store.contracts import LayoutDoc
        from uuid import uuid4

        with lock:
            job = store.get_job(job_id)
            if not job:
                raise HTTPException(404, "no such job")
            if job_id in running or job["status"] not in ("paused", "failed", "done", "waiting_voice", "paused_review"):
                raise HTTPException(409, "stop the job before replacing evidence")
            _, done = store.resume_point(job_id)
            if "laid_out" not in done:
                raise HTTPException(409, "finish layout before replacing evidence")
            directory = orch._job_dir(job_id)
            layout = directory / "layout.json"
            if not layout.exists():
                raise HTTPException(409, "layout is not available")
            original = layout.read_text(encoding="utf-8")
            doc = json.loads(original)
            target = next((e for e in doc["elements"] if e["id"] == element_id), None)
            if creating:
                if target is not None:
                    raise HTTPException(409, "element ID already exists")
                if not doc.get("board_timeline"):
                    raise HTTPException(409, "new evidence requires an authored board timeline")
                scene_ids = {e["scene_id"] for e in doc["elements"]}
                script_file = directory / "script.json"
                if script_file.exists():
                    scene_ids = {s["scene_id"] for s in json.loads(script_file.read_text(encoding="utf-8"))["scenes"]}
                if type(placement["scene_id"]) is not int or placement["scene_id"] not in scene_ids:
                    raise HTTPException(400, "unknown scene")
                target = {"id": element_id, "type": "evidence_image", "enter_action": "reveal", **placement}
                doc["elements"].append(target)
            elif target is None or target.get("type") != "evidence_image":
                raise HTTPException(404, "no such evidence slot")
            target.update(payload)
            try:
                LayoutDoc.model_validate(doc)
            except ValueError:
                raise HTTPException(400, "invalid evidence image or provenance")
            if creating:
                if (target["x"] + target["width"] > doc["canvas"]["width"]
                        or target["y"] + target["height"] > doc["canvas"]["height"]):
                    raise HTTPException(400, "evidence placement exceeds canvas")
                if not any(a["board_id"] == target["board_id"]
                           and a["start_ms"] <= target["appear_at_ms"] < a["end_ms"]
                           for a in doc["board_timeline"]["activations"]):
                    raise HTTPException(400, "selected board is not active at reveal time")
            revision = uuid4().hex
            backup = directory / ("layout.before-evidence-" + revision + ".json")
            backup.write_text(original, encoding="utf-8")
            pending = directory / ("layout.evidence-" + revision + ".pending.json")
            pending.write_text(json.dumps(doc, indent=2), encoding="utf-8")
            # Reset first: a crash can require rerendering the old layout, but cannot
            # leave the new layout marked as already rendered. Worker starts share lock.
            store.reset_from_stage(job_id, "aligned")
            pending.replace(layout)
            store.set_job_status(job_id, "paused")
            store.log(job_id, "evidence saved; alignment/render pending; backup " + backup.name)
        return {"saved": True, "element_id": element_id, "status": "paused",
                "revision": revision, "requires_realign": True}

