    @app.get("/jobs/{job_id}/events")
    async def job_events(job_id: int, token: str = "",
                         authorization: str = Header(default="")) -> dict:
        if token != _token and authorization != "Bearer %s" % _token:
            raise HTTPException(status_code=401, detail="bad token")
        q = hub.subscribe(job_id)

        async def gen():
            try:
                while True:
                    try:
                        ev = await asyncio.to_thread(q.get, True, 15)
                        yield {"event": "progress", "data": json_s(ev)}
                        if ev.get("phase") in (
                                "done", "failed", "paused", "paused_review",
                                "waiting_voice", "voice_rejected", "canceled"):
                            break
                    except queue.Empty:
                        yield {"event": "ping", "data": ""}
            finally:
                hub.unsubscribe(job_id, q)

        from fastapi.responses import StreamingResponse

        return StreamingResponse(gen(), media_type="text/event-stream")

    def json_s(obj) -> str:
        import json

        return json.dumps(obj)

    def recover_interrupted_jobs() -> None:
        with store._lock:
            rows = store.conn.execute(
                "SELECT id,status FROM jobs WHERE status IN "
                "('running','pause_requested','cancel_requested') ORDER BY id"
            ).fetchall()
        for row in rows:
            job_id, status = int(row["id"]), row["status"]
            if status == "pause_requested":
                store.set_job_status(job_id, "paused")
                store.log(job_id, "recovered requested pause after restart")
            elif status == "cancel_requested":
                store.set_job_status(job_id, "canceled")
                store.log(job_id, "completed requested cancellation after restart")
            elif orch is not None:
                store.log(job_id, "resuming interrupted job after sidecar restart")
                spawn_worker(job_id)

    app.state.hub = hub
    app.state.store = store
    return app
