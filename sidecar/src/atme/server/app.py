        if orch is None:
            raise HTTPException(503, "orchestrator not wired")
        if not store.get_job(job_id):
            raise HTTPException(404, "no such job")
        report_file = orch._job_dir(job_id) / "narration_events.json"
        if not report_file.exists():
            return {"status": "not_available", "events": []}
        try:
            events = json.loads(report_file.read_text(encoding="utf-8"))
            if not isinstance(events, list) or any(not isinstance(e, dict) for e in events):
                raise ValueError("invalid report")
        except (OSError, ValueError):
            raise HTTPException(409, "timing report is unavailable or incomplete")
        return {"status": ("no_triggers" if not events else
                           "resolved" if all(e.get("status") == "resolved" for e in events)
                           else "needs_review"), "events": events}

